# -*- coding: utf-8 -*-
"""Русская транскрипция армянских слов (восточноармянское чтение).

Армянское письмо почти фонетическое, поэтому транскрипция строится по таблице
букв с несколькими позиционными правилами. Главные особенности, из-за которых
простой таблицы мало:

  ե   в начале слова читается «йе», внутри — «е»
  ո   в начале слова читается «во», внутри — «о»
  ու  диграф, читается «у» — разбирается до таблицы
  և   лигатура «ев»
  ը   сверхкраткий нейтральный звук; в русской передаче обычно опускается
      между согласными, иначе даёт «ы»

Придыхательные (թ, փ, ք, չ, ց) и резкие (տ, պ, կ, ճ, ծ) пары в русском
не различаются — обе передаются одной буквой, разницу даёт озвучка.

  йа/йу  после согласной сливаются в йотированную букву: «-թյուն» → «-тюн»,
      а после гласной остаются раздельными: «այո» → «айо»
"""

import re

TABLE = {
    'ա': 'а',  'բ': 'б',  'գ': 'г',  'դ': 'д',  'զ': 'з',
    'է': 'э',  'թ': 'т',  'ժ': 'ж',  'ի': 'и',  'լ': 'л',
    'խ': 'х',  'ծ': 'ц',  'կ': 'к',  'հ': 'х',  'ձ': 'дз',
    'ղ': 'г',  'ճ': 'ч',  'մ': 'м',  'յ': 'й',  'ն': 'н',
    'շ': 'ш',  'չ': 'ч',  'պ': 'п',  'ջ': 'дж', 'ռ': 'р',
    'ս': 'с',  'վ': 'в',  'տ': 'т',  'ր': 'р',  'ց': 'ц',
    'ւ': 'в',  'փ': 'п',  'ք': 'к',  'օ': 'о',  'ֆ': 'ф',
}
VOWELS = set('աեէըիոօու')


def translit_word(word):
    w = word.lower()
    out, i, n = [], 0, len(w)
    while i < n:
        ch = w[i]
        nxt = w[i + 1] if i + 1 < n else ''
        start = (i == 0)

        if ch == 'ո' and nxt == 'ւ':          # диграф ու — «у»
            out.append('у'); i += 2; continue
        if ch == 'և':                          # лигатура — «ев»
            out.append('ев'); i += 1; continue
        if ch == 'ե':
            out.append('е' if start else 'е'); i += 1; continue
        if ch == 'ո':
            out.append('во' if start else 'о'); i += 1; continue
        if ch == 'ը':
            # сверхкраткий: между согласными в русской записи не передаётся
            prev = w[i - 1] if i else ''
            out.append('ы' if start or prev in VOWELS or nxt in VOWELS or not nxt else '')
            i += 1; continue

        out.append(TABLE.get(ch, ch if ch in ' -' else ''))
        i += 1
    return ''.join(out).strip()


CONS = 'бвгдзжйклмнпрстфхцчшщ'
IOTA = {'а': 'я', 'у': 'ю', 'о': 'ё', 'э': 'е'}


def merge_iota(s):
    """после согласной «й» + гласная дают одну йотированную букву"""
    return re.sub(f'(?<=[{CONS}])й([ауоэ])'.replace('й(', '(?<!й)й('),
                  lambda m: IOTA[m.group(1)], s)


def translit(text):
    return ' '.join(merge_iota(translit_word(p)) for p in str(text).split())


if __name__ == '__main__':
    CASES = [
        ('բարև', 'барев'), ('շնորհակալություն', 'шнорхакалутюн'), ('այո', 'айо'),
        ('ջուր', 'джур'), ('հաց', 'хац'), ('տուն', 'тун'), ('լավ', 'лав'),
        ('գիրք', 'гирк'), ('սիրել', 'сирел'), ('երեխա', 'ереха'),
        ('ոսկի', 'воски'), ('ուրախ', 'урах'), ('դպրոց', 'дпроц'),
    ]
    bad = 0
    for hy, expect in CASES:
        got = translit(hy)
        mark = 'ок' if got == expect else f'ОЖИДАЛОСЬ {expect}'
        if got != expect: bad += 1
        print(f'  {hy:22} {got:22} {mark}')
    print(f'\nрасхождений: {bad} из {len(CASES)}')
